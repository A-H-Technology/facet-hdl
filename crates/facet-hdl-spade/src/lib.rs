//! Spade from a [`facet_hdl::Boundary`], compiled to SystemVerilog
//! in-process.
//!
//! [`Spade::of`] gives two Spade files: [`LIBRARY`] (`facet_hdl.spade`, the
//! AXI4 slave and shared types) and the boundary's own module: one Spade type
//! per Rust type, `pack_*`/`unpack_*` functions mirroring
//! `facet_hdl::codec`, and the `<boundary>_regs` entity. Fabric logic written
//! in Spade instantiates that entity with typed ports. [`compile`] turns it
//! all into SystemVerilog, which chipsmith reads.

mod compile;
mod literal;
mod names;
mod regs;
mod types;

use facet::Facet;
use facet_hdl::{Boundary, LayoutError};
use std::path::{Path, PathBuf};

pub use compile::{Source, compile};
pub use literal::literal;
pub use names::NameError;
pub use regs::{entity_name, ports_name};

/// `facet_hdl.spade`: compiled as the module `facet_hdl`.
pub const LIBRARY: &str = include_str!("../spade/facet_hdl.spade");

pub struct Spade {
    /// The module the boundary's file is compiled as (`calc` for `Calc`).
    pub module: String,
    pub entity_name: String,
    pub code: String,
}

impl Spade {
    pub fn of<B: Facet<'static>>() -> Result<Self, Error> {
        Self::from_boundary(&Boundary::of::<B>()?)
    }

    pub fn from_boundary(b: &Boundary) -> Result<Self, Error> {
        let mut used = Vec::new();
        for p in &b.ports {
            types::collect(&p.ty, &mut used);
        }
        let module = names::snake(b.name);
        let code = format!(
            "// Generated by facet-hdl from `{name}`. Do not edit; change the Rust\n// declaration and regenerate.\n//\n// Layout:\n{layout}\n{types}{regs}",
            name = b.name,
            layout = b.canonical().lines().map(|l| format!("//   {l}\n")).collect::<String>(),
            types = types::generate(&used)?,
            regs = regs::generate(b)?,
        );
        Ok(Self {
            module,
            entity_name: regs::entity_name(b),
            code,
        })
    }

    /// Compiles `top` with the library and this boundary into SystemVerilog.
    pub fn compile(&self, top: &str) -> Result<String, String> {
        self.compile_with(top, &[])
    }

    /// Like [`Spade::compile`], with more of your own modules alongside (each
    /// [`Source::module`] names the module it's compiled as).
    pub fn compile_with(&self, top: &str, more: &[Source<'_>]) -> Result<String, String> {
        let module = [self.module.as_str()];
        let file = format!("{}.spade", self.module);
        let mut sources = vec![
            Source {
                module: &[],
                name: "top.spade",
                code: top,
            },
            Source {
                module: &["facet_hdl"],
                name: "facet_hdl.spade",
                code: LIBRARY,
            },
            Source {
                module: &module,
                name: &file,
                code: &self.code,
            },
        ];
        sources.extend(more.iter().map(|s| Source { ..*s }));
        compile(&sources)
    }

    /// Writes `facet_hdl.spade` and `<module>.spade` into `dir`, for a swim
    /// project's `src/`.
    pub fn write_to(&self, dir: &Path) -> std::io::Result<[PathBuf; 2]> {
        std::fs::create_dir_all(dir)?;
        let files = [
            (dir.join("facet_hdl.spade"), LIBRARY),
            (dir.join(format!("{}.spade", self.module)), self.code.as_str()),
        ];
        for (path, text) in &files {
            std::fs::write(path, text)?;
        }
        Ok(files.map(|(path, _)| path))
    }
}

