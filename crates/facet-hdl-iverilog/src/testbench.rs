//! The generated testbench: an AXI4 master driven by line commands on stdin.

/// Inputs change on the falling edge and handshakes are judged 1 ns before
/// the rising one, so the testbench never races the design's flops.
pub fn testbench(top: &str, irq: bool) -> String {
    let irq_port = if irq { ", .irq(irq)" } else { "" };
    format!(
        r#"// Generated by facet-hdl-iverilog: stdin/stdout AXI4 master for co-simulation.
//   (every reply starts with "@@ " so the simulator's own output can't be mistaken for one)
//   W <word> <hex32>           -> "B <resp>"
//   R <word>                   -> "D <hex32> <resp>"
//   X <word> <n> <hex32>...    -> "B <resp>"            n-beat write burst
//   Y <word> <n>               -> "Y <hex32>... <resp>" n-beat read burst
//   T <cycles>                 -> "T"
//   I <cycles>                 -> "I <0|1>": waits up to <cycles> for irq, then reports it
//   Q                          -> ends the simulation
// A response whose ID isn't the request's, or a read burst whose RLAST
// isn't on its last beat, is reported as resp 9.
`timescale 1ns/1ps
`default_nettype none
module {TB};
  localparam integer STDIN = 32'h8000_0000;
  reg clk = 0;
  always #5 clk = ~clk;
  reg rst = 1;

  reg [3:0] awid = 0, arid = 0, id = 0;
  reg [31:0] awaddr = 0, araddr = 0, wdata = 0;
  reg [7:0] awlen = 0, arlen = 0;
  reg awvalid = 0, wvalid = 0, bready = 0, arvalid = 0, rready = 0;
  wire awready, wready, bvalid, arready, rvalid, rlast;
  wire [3:0] bid, rid;
  wire [1:0] bresp, rresp;
  wire [31:0] rdata;
  wire irq;

  {top} dut (
    .clk(clk), .rst(rst),
    .s_axi_awid(awid), .s_axi_awaddr(awaddr), .s_axi_awlen(awlen), .s_axi_awvalid(awvalid), .s_axi_awready(awready),
    .s_axi_wdata(wdata), .s_axi_wvalid(wvalid), .s_axi_wready(wready),
    .s_axi_bid(bid), .s_axi_bresp(bresp), .s_axi_bvalid(bvalid), .s_axi_bready(bready),
    .s_axi_arid(arid), .s_axi_araddr(araddr), .s_axi_arlen(arlen), .s_axi_arvalid(arvalid), .s_axi_arready(arready),
    .s_axi_rid(rid), .s_axi_rdata(rdata), .s_axi_rresp(rresp), .s_axi_rlast(rlast), .s_axi_rvalid(rvalid), .s_axi_rready(rready){irq_port}
  );

  // Just before the next rising edge: what the design will sample there.
  task pre_edge;
    begin
      @(negedge clk);
      #4;
    end
  endtask

  integer word, n, i, code, resp;
  reg [31:0] data;
  reg [8*8-1:0] cmd;
  reg aw_done, w_done, got;
  reg bad;

  task write_burst(input integer at, input integer beats);
    begin
      id = id + 1;
      @(negedge clk);
      awid = id; awaddr = at * 4; awlen = beats - 1; awvalid = 1;
      aw_done = 0;
      while (!aw_done) begin
        #4;
        if (awready) aw_done = 1;
        @(negedge clk);
      end
      awvalid = 0;
      for (i = 0; i < beats; i = i + 1) begin
        code = $fscanf(STDIN, "%h", data);
        wdata = data; wvalid = 1;
        w_done = 0;
        while (!w_done) begin
          #4;
          if (wready) w_done = 1;
          @(negedge clk);
        end
        wvalid = 0;
      end
      bready = 1;
      got = 0;
      while (!got) begin
        #4;
        if (bvalid) begin
          got = 1;
          resp = (bid == id) ? bresp : 9;
        end
        @(negedge clk);
      end
      bready = 0;
    end
  endtask

  task read_burst(input integer at, input integer beats);
    begin
      id = id + 1;
      @(negedge clk);
      arid = id; araddr = at * 4; arlen = beats - 1; arvalid = 1;
      got = 0;
      while (!got) begin
        #4;
        if (arready) got = 1;
        @(negedge clk);
      end
      arvalid = 0;
      rready = 1;
      bad = 0;
      resp = 0;
      for (i = 0; i < beats; i = i + 1) begin
        got = 0;
        while (!got) begin
          #4;
          if (rvalid) begin
            got = 1;
            $write(" %08h", rdata);
            if (rid != id || rlast != (i == beats - 1)) bad = 1;
            if (rresp != 0) resp = rresp;
          end
          @(negedge clk);
        end
      end
      rready = 0;
      if (bad) resp = 9;
    end
  endtask

  // `vvp sim.vvp +vcd=<file>` dumps every signal, for chasing a bug by hand.
  reg [8*256-1:0] vcd_file;
  initial begin
    if ($value$plusargs("vcd=%s", vcd_file)) begin
      $dumpfile(vcd_file);
      $dumpvars(0, dut);
    end
  end

  initial begin
    repeat (4) @(posedge clk);
    @(negedge clk);
    rst = 0;
    @(posedge clk);
    $display("@@ READY");
    $fflush;
    forever begin
      code = $fscanf(STDIN, "%s", cmd);
      if (code != 1) $finish;
      case (cmd[7:0])
        "W": begin
          code = $fscanf(STDIN, "%d", word);
          write_burst(word, 1);
          $display("@@ B %0d", resp);
        end
        "X": begin
          code = $fscanf(STDIN, "%d %d", word, n);
          write_burst(word, n);
          $display("@@ B %0d", resp);
        end
        "R": begin
          code = $fscanf(STDIN, "%d", word);
          $write("@@ D");
          read_burst(word, 1);
          $display(" %0d", resp);
        end
        "Y": begin
          code = $fscanf(STDIN, "%d %d", word, n);
          $write("@@ Y");
          read_burst(word, n);
          $display(" %0d", resp);
        end
        "T": begin
          code = $fscanf(STDIN, "%d", n);
          repeat (n) @(posedge clk);
          $display("@@ T");
        end
        "I": begin
          code = $fscanf(STDIN, "%d", n);
          for (i = 0; i < n && irq !== 1'b1; i = i + 1) @(posedge clk);
          $display("@@ I %0d", irq === 1'b1);
        end
        default: $finish;
      endcase
      $fflush;
    end
  end
endmodule
"#,
        TB = super::TB
    )
}
